# ============================================================
# FUZZY MATCH
# ============================================================

def fuzzy_province(ocr_text):

    # ตัดช่องว่าง
    text = ocr_text.strip()

    if not text:
        return None, 0

    # หาคำที่ใกล้ที่สุด
    result = process.extractOne(
        text,
        PROVINCES,
        scorer=fuzz.ratio
    )

    if result is None:
        return None, 0

    province, score, _ = result

    # ผ่าน Threshold
    if score >= FUZZY_THRESHOLD:
        return province, score

    # ไม่ผ่าน
    return None, score


# ============================================================
# MAIN
# ============================================================

def main():

    print("=" * 55)
    print("Province Fuzzy String Matching")
    print("=" * 55)

    while True:

        text = input("\nOCR Result (พิมพ์ exit เพื่อออก): ").strip()

        if text.lower() == "exit":
            break

        province, score = fuzzy_province(text)

        print("-" * 55)
        print(f"OCR Text        : {text}")
        print(f"Similarity      : {score:.2f}%")
        print(f"Threshold       : {FUZZY_THRESHOLD}%")

        if province is not None:
            print(f"Matched Province: {province}")
            print("Result          : PASS")
        else:
            print("Matched Province: ไม่พบ")
            print("Result          : REJECT")

        print("-" * 55)


# ============================================================
# RUN
# ============================================================

if __name__ == "__main__":
    main()